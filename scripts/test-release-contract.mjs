#!/usr/bin/env node

import { mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const verifier = join(root, "scripts", "verify-release-contract.mjs");

function cargo(version, extraPackageLines = "") {
  return `[package]\nname = "relay-contract-fixture"\nversion = "${version}"\nedition = "2024"\n${extraPackageLines}\n[lib]\npath = "fixture.rs"\n`;
}

function cargoLock(packages) {
  const entries = packages
    .map(({ name, version }) => `[[package]]\nname = "${name}"\nversion = "${version}"\n`)
    .join("\n");
  return `# This file is automatically @generated by Cargo.\nversion = 4\n${entries ? `\n${entries}` : ""}`;
}

async function writeStandaloneCargo(cargoPath, version, extraPackageLines = "") {
  await Promise.all([
    writeFile(cargoPath, cargo(version, extraPackageLines)),
    writeFile(join(dirname(cargoPath), "fixture.rs"), ""),
    writeFile(
      join(dirname(cargoPath), "Cargo.lock"),
      cargoLock([{ name: "relay-contract-fixture", version }])
    )
  ]);
}

function run(cargoPath, eventName, refType, refName, githubOutput, environment = process.env) {
  const arguments_ = [
    verifier,
    "--cargo",
    cargoPath,
    "--event-name",
    eventName,
    "--ref-type",
    refType,
    "--ref-name",
    refName
  ];
  if (githubOutput) arguments_.push("--github-output", githubOutput);
  return spawnSync(process.execPath, arguments_, {
    cwd: root,
    encoding: "utf8",
    env: environment
  });
}

function expectStatus(result, status, label) {
  if (result.status !== status) {
    throw new Error(
      `${label}: expected exit ${status}, received ${result.status}: ${result.stderr || result.stdout}`
    );
  }
}

function expectRejected(result, label, reason) {
  expectStatus(result, 1, label);
  const expected = `release contract rejected: ${reason}`;
  if (result.stderr.trim() !== expected) {
    throw new Error(
      `${label}: expected stderr ${JSON.stringify(expected)}, received ${JSON.stringify(result.stderr.trim())}`
    );
  }
}

const fixture = await mkdtemp(join(tmpdir(), "relay-release-contract-test-"));
try {
  const cargoPath = join(fixture, "Cargo.toml");
  const outputPath = join(fixture, "github-output");
  await writeStandaloneCargo(cargoPath, "0.2.0-rc.9");
  await writeFile(outputPath, "existing=value\n");

  const tagPush = run(cargoPath, "push", "tag", "v0.2.0-rc.9", outputPath);
  expectStatus(tagPush, 0, "matching tag push");
  if ((await readFile(outputPath, "utf8")) !== "existing=value\nversion=0.2.0-rc.9\n") {
    throw new Error("matching tag push did not append the exact release version output");
  }

  expectStatus(run(cargoPath, "workflow_dispatch", "branch", "main"), 0, "manual branch");
  expectStatus(
    run(cargoPath, "workflow_dispatch", "tag", "v0.2.0-rc.9"),
    0,
    "manual matching tag"
  );
  await writeFile(cargoPath, cargo("0.2.0-rc.9").replaceAll("\n", "\r\n"));
  expectStatus(run(cargoPath, "push", "tag", "v0.2.0-rc.9"), 0, "CRLF Cargo.toml");
  await writeFile(cargoPath, cargo("0.2.0-rc.9").replace('"0.2.0-rc.9"', "'0.2.0-rc.9'"));
  expectStatus(
    run(cargoPath, "push", "tag", "v0.2.0-rc.9"),
    0,
    "single-quoted literal package version"
  );
  await writeFile(
    cargoPath,
    cargo(
      "0.2.0-rc.9",
      'description = """\nversion = "9.9.9"\nThis is data, not a package key.\n"""\n'
    )
  );
  expectStatus(
    run(cargoPath, "push", "tag", "v0.2.0-rc.9"),
    0,
    "version-shaped text inside a multiline string"
  );
  await writeStandaloneCargo(cargoPath, "0.2.0-rc.9");

  const workspacePath = join(fixture, "workspace");
  const workspaceMemberPath = join(workspacePath, "member");
  const workspaceCargoPath = join(workspacePath, "Cargo.toml");
  const memberCargoPath = join(workspaceMemberPath, "Cargo.toml");
  const workspaceOutputPath = join(workspacePath, "github-output");
  await mkdir(workspaceMemberPath, { recursive: true });
  await writeFile(
    workspaceCargoPath,
    `[workspace]\nmembers = ["member"]\nresolver = "3"\n\n[workspace.package]\nversion = "4.5.6"\nedition = "2024"\n\n[package]\nname = "relay-workspace-root"\nversion = "8.8.8"\nedition = "2024"\n\n[lib]\npath = "workspace-root.rs"\n`
  );
  await writeFile(
    memberCargoPath,
    `[package]\nname = "relay-workspace-member"\nversion.workspace = true\nedition.workspace = true\n\n[lib]\npath = "member.rs"\n`
  );
  await writeFile(join(workspacePath, "workspace-root.rs"), "");
  await writeFile(join(workspaceMemberPath, "member.rs"), "");
  await writeFile(
    join(workspacePath, "Cargo.lock"),
    cargoLock([
      { name: "relay-workspace-member", version: "4.5.6" },
      { name: "relay-workspace-root", version: "8.8.8" }
    ])
  );
  await writeFile(workspaceOutputPath, "existing=workspace\n");
  expectStatus(
    run(memberCargoPath, "push", "tag", "v4.5.6", workspaceOutputPath),
    0,
    "workspace-inherited package version"
  );
  if (
    (await readFile(workspaceOutputPath, "utf8")) !==
    "existing=workspace\nversion=4.5.6\n"
  ) {
    throw new Error("workspace package did not resolve its inherited version exactly");
  }

  const rejected = [
    [
      "push",
      "tag",
      "v0.2.0-rc.8",
      "mismatched tag",
      "release tag does not exactly match the Cargo package version"
    ],
    ["push", "branch", "main", "branch push", "release push must be a tag ref"],
    [
      "workflow_dispatch",
      "tag",
      "v0.2.0",
      "manual mismatched tag",
      "release tag does not exactly match the Cargo package version"
    ],
    [
      "workflow_dispatch",
      "commit",
      "deadbeef",
      "manual unsupported ref",
      "manual release ref must be a branch or tag"
    ],
    ["pull_request", "branch", "main", "unsupported event", "unsupported release event"]
  ];
  for (const [eventName, refType, refName, label, reason] of rejected) {
    expectRejected(run(cargoPath, eventName, refType, refName), label, reason);
  }

  const failureOutputPath = join(fixture, "failure-output");
  const fakeCargoDirectory = join(fixture, "fake-cargo-bin");
  const fakeCargoPath = join(fakeCargoDirectory, "cargo");
  const fakeCargoEnvironment = {
    ...process.env,
    PATH: `${fakeCargoDirectory}:${process.env.PATH ?? ""}`
  };
  await mkdir(fakeCargoDirectory);
  await writeFile(failureOutputPath, "sentinel=unchanged\n");
  await writeFile(
    fakeCargoPath,
    '#!/bin/sh\nprintf \'private cargo diagnostic: /sensitive/repository/Cargo.toml\\n\' >&2\nexit 19\n',
    { mode: 0o755 }
  );
  expectRejected(
    run(
      cargoPath,
      "push",
      "tag",
      "v0.2.0-rc.9",
      failureOutputPath,
      fakeCargoEnvironment
    ),
    "private Cargo failure",
    "Cargo metadata could not resolve the validated manifest"
  );
  if ((await readFile(failureOutputPath, "utf8")) !== "sentinel=unchanged\n") {
    throw new Error("Cargo metadata failure modified the GitHub output file");
  }

  await writeFile(
    fakeCargoPath,
    '#!/usr/bin/env node\nprocess.stdout.write(Buffer.alloc(2 * 1024 * 1024));\n',
    { mode: 0o755 }
  );
  expectRejected(
    run(
      cargoPath,
      "push",
      "tag",
      "v0.2.0-rc.9",
      failureOutputPath,
      fakeCargoEnvironment
    ),
    "oversized Cargo metadata output",
    "Cargo metadata exceeded the release contract output limit"
  );
  if ((await readFile(failureOutputPath, "utf8")) !== "sentinel=unchanged\n") {
    throw new Error("oversized Cargo metadata output modified the GitHub output file");
  }

  await writeFile(
    fakeCargoPath,
    `#!/usr/bin/env node
const fs = require("node:fs");
const manifestPath = process.argv.at(-1);
fs.appendFileSync(manifestPath, "\\n# changed while Cargo metadata ran\\n");
process.stdout.write(JSON.stringify({
  packages: [{
    manifest_path: fs.realpathSync(manifestPath),
    version: "0.2.0-rc.9"
  }]
}));
`,
    { mode: 0o755 }
  );
  expectRejected(
    run(
      cargoPath,
      "push",
      "tag",
      "v0.2.0-rc.9",
      failureOutputPath,
      fakeCargoEnvironment
    ),
    "Cargo.toml changed during metadata",
    "Cargo.toml changed or became unsafe while metadata was read"
  );
  if ((await readFile(failureOutputPath, "utf8")) !== "sentinel=unchanged\n") {
    throw new Error("a Cargo.toml change during metadata modified the GitHub output file");
  }
  await writeStandaloneCargo(cargoPath, "0.2.0-rc.9");

  for (const invalid of ["01.2.3", "1.02.3", "1.2", "1.2.3-01", "1.2.3-"]) {
    await writeFile(cargoPath, cargo(invalid));
    expectRejected(
      run(cargoPath, "push", "tag", `v${invalid}`),
      `invalid SemVer ${invalid}`,
      "Cargo metadata could not resolve the validated manifest"
    );
  }

  await writeFile(cargoPath, cargo("1.2.3", 'version = "9.9.9"'));
  expectRejected(
    run(cargoPath, "push", "tag", "v1.2.3"),
    "duplicate package version",
    "Cargo metadata could not resolve the validated manifest"
  );

  await writeFile(cargoPath, cargo("1.2.3", "version = '9.9.9'"));
  expectRejected(
    run(cargoPath, "push", "tag", "v1.2.3"),
    "mixed-quote duplicate package version",
    "Cargo metadata could not resolve the validated manifest"
  );

  const oversizedVersion = `1.2.3-${"a".repeat(257)}`;
  await writeStandaloneCargo(cargoPath, oversizedVersion);
  expectRejected(
    run(cargoPath, "push", "tag", `v${oversizedVersion}`),
    "oversized version",
    "Cargo package version is not valid SemVer"
  );

  await writeStandaloneCargo(cargoPath, "1.2.3");
  await writeFile(cargoPath, `${cargo("1.2.3")}#${"x".repeat(1024 * 1024)}`);
  expectRejected(
    run(cargoPath, "push", "tag", "v1.2.3"),
    "oversized Cargo.toml",
    "Cargo.toml must be a regular non-symlink file within the size limit"
  );

  const symlinkTarget = join(fixture, "Cargo.target.toml");
  const symlinkPath = join(fixture, "Cargo.symlink.toml");
  await writeFile(symlinkTarget, cargo("1.2.3"));
  await symlink(symlinkTarget, symlinkPath);
  expectRejected(
    run(symlinkPath, "push", "tag", "v1.2.3"),
    "symlinked Cargo.toml",
    "Cargo.toml must be a regular non-symlink file within the size limit"
  );

  const directoryPath = join(fixture, "Cargo.directory.toml");
  await mkdir(directoryPath);
  expectRejected(
    run(directoryPath, "push", "tag", "v1.2.3"),
    "directory Cargo.toml",
    "Cargo.toml must be a regular non-symlink file within the size limit"
  );

  await writeFile(cargoPath, `[workspace]\nmembers = []\n`);
  await writeFile(join(fixture, "Cargo.lock"), cargoLock([]));
  expectRejected(
    run(cargoPath, "push", "tag", "v1.2.3"),
    "missing package section",
    "Cargo metadata did not return exactly one package for the validated manifest"
  );
} finally {
  await rm(fixture, { recursive: true, force: true });
}

process.stdout.write("Verified release tag and Cargo version contracts.\n");
